"""Measure how well ChartVoice extracts values from charts with known data.

    cd backend
    venv\\Scripts\\activate
    python ../eval/run_eval.py

For every eval/charts/<name>.png with eval/ground_truth/<name>.csv, runs
DePlot + parsing, matches rows by label and counts values within 5% of the
truth. Writes eval/results.md. Numbers come only from actually running this.
"""

import csv
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "backend"))

from PIL import Image  # noqa: E402

from app.extraction.deplot import DePlotModel  # noqa: E402
from app.extraction.parse import parse_table  # noqa: E402

TOLERANCE = 0.05


def norm(label) -> str:
    return str(label).strip().lower()


def load_truth(path: Path) -> tuple[list[str], dict[str, list[float]]]:
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    header, body = rows[0], rows[1:]
    return header, {norm(r[0]): [float(v) for v in r[1:]] for r in body}


def score(parsed, truth: dict[str, list[float]]) -> tuple[int, int, bool]:
    extracted = {norm(r[0]): r[1:] for r in parsed.rows}
    correct = total = 0
    for label, true_values in truth.items():
        got = extracted.get(label, [])
        for i, true_value in enumerate(true_values):
            total += 1
            value = got[i] if i < len(got) else None
            if isinstance(value, (int, float)) and abs(value - true_value) <= TOLERANCE * max(abs(true_value), 1e-9):
                correct += 1
    true_max = max(truth, key=lambda k: truth[k][0])
    numeric = [(k, v[0]) for k, v in extracted.items() if v and isinstance(v[0], (int, float))]
    max_ok = bool(numeric) and max(numeric, key=lambda kv: kv[1])[0] == true_max
    return correct, total, max_ok


def main() -> None:
    charts = sorted(p for p in (ROOT / "charts").glob("*.png") if (ROOT / "ground_truth" / f"{p.stem}.csv").exists())
    if not charts:
        sys.exit("No charts found. Run: python eval/make_charts.py")

    print("Loading DePlot (first run downloads the weights)...")
    start = time.perf_counter()
    model = DePlotModel()
    print(f"Loaded in {time.perf_counter() - start:.1f} s\n")

    lines, seconds = [], []
    all_correct = all_total = max_hits = 0
    for path in charts:
        _, truth = load_truth(ROOT / "ground_truth" / f"{path.stem}.csv")
        t0 = time.perf_counter()
        raw = model.extract(Image.open(path))
        seconds.append(time.perf_counter() - t0)
        parsed = parse_table(raw)
        correct, total, max_ok = score(parsed, truth)
        all_correct += correct
        all_total += total
        max_hits += max_ok
        print(f"{path.stem:10s} {correct:2d}/{total:<2d} values  max {'ok ' if max_ok else 'MISS'}  {seconds[-1]:5.1f} s")
        print(f"           raw: {raw[:150]}")
        lines.append(f"| {path.stem} | {correct}/{total} | {'yes' if max_ok else 'no'} | {seconds[-1]:.1f} |")

    accuracy = all_correct / all_total * 100
    median = statistics.median(seconds)
    print(f"\nValues within 5%: {all_correct}/{all_total} ({accuracy:.0f}%)")
    print(f"Highest value identified: {max_hits}/{len(charts)}")
    print(f"Median seconds per chart: {median:.1f}")

    report = [
        "# ChartVoice evaluation results",
        "",
        f"Charts: {len(charts)} (generated by `eval/make_charts.py` with known data). Tolerance: 5%.",
        "",
        f"- Values within 5%: **{all_correct}/{all_total} ({accuracy:.0f}%)**",
        f"- Highest value identified correctly: **{max_hits}/{len(charts)}**",
        f"- Median extraction time: **{median:.1f} s** per chart (CPU)",
        "",
        "| Chart | Values within 5% | Highest correct | Seconds |",
        "| --- | --- | --- | --- |",
        *lines,
    ]
    (ROOT / "results.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"\nWrote {ROOT / 'results.md'}")


if __name__ == "__main__":
    main()
